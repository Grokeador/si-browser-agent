#!/usr/bin/env python3
"""
SI-Browser-Agent (by SI NEWS) — Zero-API Browser-Use .env, 16k Modelfile & Chrome CDP Generator.
Standard library only.
"""
from __future__ import annotations
import argparse
import sys
from pathlib import Path
from typing import Dict, List


def recommend_model_for_vram(vram_gb: int) -> Dict[str, str]:
    if vram_gb >= 16:
        return {"provider": "ollama", "base_model": "qwen2.5:14b", "ctx": "32768", "custom_name": "si-agent-32k"}
    if vram_gb >= 8:
        return {"provider": "ollama", "base_model": "qwen2.5:7b", "ctx": "16384", "custom_name": "si-agent-16k"}
    return {"provider": "google", "base_model": "gemini-2.0-flash", "ctx": "32768", "custom_name": "gemini-2.0-flash"}


def generate_ollama_modelfile(base_model: str = "qwen2.5:14b", num_ctx: int = 16384) -> str:
    return (
        f"FROM {base_model}\n"
        f"PARAMETER num_ctx {int(num_ctx)}\n"
        "PARAMETER temperature 0.1\n"
        "PARAMETER top_p 0.9\n"
        "PARAMETER repeat_penalty 1.05\n"
    )


def generate_browser_use_env(vram_gb: int = 12, cdp_port: int = 9222) -> str:
    rec = recommend_model_for_vram(vram_gb)
    return (
        f"# Generated by SI-Browser-Agent (https://github.com/Grokeador/si-browser-agent)\n"
        f"DEFAULT_LLM_PROVIDER={rec['provider']}\n"
        f"DEFAULT_MODEL_NAME={rec['custom_name']}\n"
        f"OLLAMA_ENDPOINT=http://localhost:11434\n"
        f"OLLAMA_NUM_CTX={rec['ctx']}\n"
        f"BROWSER_HEADLESS=false\n"
        f"KEEP_BROWSER_OPEN=true\n"
        f"CHROME_CDP=http://localhost:{int(cdp_port)}\n"
    )


def generate_chrome_cdp_bat(profile_dir: str = "C:/ChromeAgentProfile", port: int = 9222) -> str:
    norm_dir = profile_dir.replace("\\", "/")
    return (
        "@echo off\n"
        "REM SI-Browser-Agent Isolated Chrome CDP Launcher\n"
        'set "CHROME_EXE=C:/Program Files/Google/Chrome/Application/chrome.exe"\n'
        f'"%CHROME_EXE%" --remote-debugging-port={int(port)} --user-data-dir="{norm_dir}" --no-first-run\n'
    )


def main(argv: List[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="SI-Browser-Agent Setup CLI (by SI NEWS)")
    parser.add_argument("--vram", type=int, default=12, help="GPU VRAM in GB (e.g. 4, 8, 12, 16)")
    parser.add_argument("--out-dir", type=str, help="Directory to write .env, Modelfile, and Chrome BAT")
    args = parser.parse_args(argv)

    rec = recommend_model_for_vram(args.vram)
    env_txt = generate_browser_use_env(args.vram)
    mf_txt = generate_ollama_modelfile(rec["base_model"], int(rec["ctx"]))
    bat_txt = generate_chrome_cdp_bat()

    if args.out_dir:
        out = Path(args.out_dir)
        out.mkdir(parents=True, exist_ok=True)
        (out / ".env.example").write_text(env_txt, encoding="utf-8")
        (out / "Modelfile.agent16k").write_text(mf_txt, encoding="utf-8")
        (out / "launch_agent_chrome.bat").write_text(bat_txt, encoding="utf-8")
        print(f"[OK] Wrote .env.example, Modelfile.agent16k, and launch_agent_chrome.bat to {out}")
    else:
        print(env_txt)
    return 0


if __name__ == "__main__":
    sys.exit(main())
